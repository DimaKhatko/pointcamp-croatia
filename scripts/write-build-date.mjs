// Writes src/lib/buildDate.generated.ts with today's calendar date in Europe/Kyiv.
// Runs before every `build` (see package.json). The price skeletons are sized from
// the price tier current on this date, so the site must be rebuilt on each tier
// switch date (see CLAUDE.md, "Pricing"). BUILD_DATE=YYYY-MM-DD overrides the date
// (for testing a build as if it ran on another day).
import { writeFileSync } from "node:fs";

function kyivToday() {
  for (const timeZone of ["Europe/Kyiv", "Europe/Kiev"]) {
    try {
      const parts = new Intl.DateTimeFormat("en-CA", {
        timeZone,
        year: "numeric",
        month: "2-digit",
        day: "2-digit",
      }).formatToParts(new Date());
      const get = (type) => parts.find((p) => p.type === type)?.value ?? "";
      return `${get("year")}-${get("month")}-${get("day")}`;
    } catch {
      // try the next zone name
    }
  }
  return new Date().toISOString().slice(0, 10);
}

const date = process.env.BUILD_DATE || kyivToday();
if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
  throw new Error(`BUILD_DATE must be YYYY-MM-DD, got "${date}"`);
}

const out = new URL("../src/lib/buildDate.generated.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/write-build-date.mjs before every build. Do not edit.\n` +
    `// Calendar date of the build in Europe/Kyiv; sizes the price skeletons.\n` +
    `export const BUILD_DATE = "${date}";\n`,
);
console.log(`build date (Kyiv): ${date}`);
